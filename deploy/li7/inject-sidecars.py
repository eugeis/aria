#!/usr/bin/env python3
"""Idempotently inject the li7-only bits into the rendered helm chart.

The chart under deploy/li7/helm is GENERATED by the mosaic render (the
`aria-ask` sidecar — the hand-written Alexa surface — is an app concern, not
a mosaic concern), so every fresh render drops it. Run this after every
render:

    python3 inject-sidecars.py <helm-dir> [image-tag]   # tag default: latest

It (re)adds:
  * the `aria-ask` container (the ASK protocol + /stream + /art + the scanner)
  * the hostPath mounts the pod actually needs on li7:
      /var/lib/aria-media   -> /media   (the audio files; both containers)
      /var/lib/aria-data    -> /data    (knowledge base; both containers —
                                         the adapter publishes the scan there,
                                         the brain ingests it)
      /var/lib/aria-lancedb -> /vector  (embedded LanceDB; brain only)
    (the render's dataPvc /data mount is kept conditional — on li7 the PVC
    is disabled and the host paths carry the data)
  * the named service ports (api + ask)
  * the ingress path split (/alexa, /stream, /art -> ask; the rest -> api)
  * a no-surge rollout strategy (li7 is memory-tight — an old aria pod and
    its replacement may never be scheduled at the same time)

Everything is baked into the template so ONE `helm upgrade` produces the
final pod spec — a post-helm `kubectl patch` would mutate the template a
second time, spawn a second ReplicaSet, and (with the no-surge strategy
still rolling the first) leave two pods reserving memory they cannot both
get. Skips cleanly when already present.
"""
import re
import sys
import pathlib

SIDECAR = """
        # li7-only sidecar (injected by deploy/li7/inject-sidecars.py — the
        # chart itself is render-generated): the ASK surface. The ingress
        # routes /alexa, /stream/*, /art/* here (port 8090); everything else
        # goes to the brain (port {{ .Values.containerPort }}).
        - name: aria-ask
          image: mosaic/aria-ask:__TAG__
          imagePullPolicy: Never
          ports:
            - containerPort: 8090
          env:
            # The baked config (adapter/config/aria.example.toml) carries the
            # collection paths + scan output; the secrets ride the env.
            - name: ARIA_PUBLIC_URL
              value: "https://aria.eisler-systems.de"
            - name: ARIA_DATA_DIR
              value: /data/adapter
            - name: ARIA_BRAIN_URL
              value: "http://127.0.0.1:3000"
            - name: ARIA_BRAIN_TOKEN
              valueFrom:
                secretKeyRef:
                  # The brain's `adapter` service-account secret (the same
                  # value the app validates as MOAIC_ADAPTER_TOKEN).
                  name: moaic-adapter-token
                  key: MOAIC_ADAPTER_TOKEN
            # The Alexa skill client id (Endpoint configuration → Client ID).
            # Empty = the check is off; set it once the skill is registered:
            #   kubectl -n aria set env deploy/aria -c aria-ask ARIA_CLIENT_ID=amzn1.ask.skill.…
            - name: ARIA_CLIENT_ID
              value: ""
          readinessProbe:
            httpGet:
              path: /health
              port: 8090
            initialDelaySeconds: 5
            periodSeconds: 10
          resources:
            requests:
              cpu: 100m
              # The adapter is a small streaming proxy (RSS ~30-50 Mi) —
              # 128 Mi keeps the TOTAL pod request under the headroom a
              # fully-occupied li7 node leaves for it (see the tessera
              # resources comment).
              memory: 128Mi
            limits:
              memory: 1Gi
          volumeMounts:
            {{- if and .Values.dataPvc .Values.dataPvc.enabled }}
            - name: data
              mountPath: /data
            {{- end }}
            # li7 (injected by inject-sidecars.py): the scan publishes into
            # /data/knowledge; the audio files stream from /media.
            - name: host-data
              mountPath: /data
            - name: media
              mountPath: /media
"""

# The brain container's dataPvc-conditional /data mount — the render's ONLY
# brain mount. It is replaced by an always-on block (hostPath /data +
# /vector) followed by the aria-ask sidecar. One replacement, one template
# generation.
BRAIN_MOUNTS_OLD = """          {{- if and .Values.dataPvc .Values.dataPvc.enabled }}
          volumeMounts:
            - name: data
              mountPath: /data
          {{- end }}
"""

BRAIN_MOUNTS_PRELUDE = """          volumeMounts:
            {{- if and .Values.dataPvc .Values.dataPvc.enabled }}
            - name: data
              mountPath: /data
            {{- end }}
            # li7 (injected by inject-sidecars.py): the knowledge base (the
            # adapter publishes /data/knowledge/media; the brain ingests it)
            # + the embedded LanceDB — both on host directories.
            - name: host-data
              mountPath: /data
            - name: host-vector
              mountPath: /vector
"""

VOLUMES_OLD = """      {{- if and .Values.dataPvc .Values.dataPvc.enabled }}
      volumes:
        - name: data
          persistentVolumeClaim:
            claimName: {{ include "aria.fullname" . }}-data
      {{- end }}"""

VOLUMES_NEW = """      volumes:
        {{- if and .Values.dataPvc .Values.dataPvc.enabled }}
        - name: data
          persistentVolumeClaim:
            claimName: {{ include "aria.fullname" . }}-data
        {{- end }}
        # li7 (injected): the audio files — a hostPath on the li7 host
        # (the music/audiobook/sermon collections live there, mounted at
        # /media in the pod; the adapter streams + scans them).
        # DirectoryOrCreate: an empty /media just means an empty catalog.
        - name: media
          hostPath:
            path: /var/lib/aria-media
            type: DirectoryOrCreate
        # li7 (injected): the knowledge base (the scan's media.jsonl.gz,
        # the sermon scripts) + the embedded LanceDB. Plain Directory: a
        # mis-typed path must fail loudly, not mount an empty dir.
        - name: host-data
          hostPath:
            path: /var/lib/aria-data
            type: Directory
        - name: host-vector
          hostPath:
            path: /var/lib/aria-lancedb
            type: Directory"""

SVC_PORTS_NEW = """  ports:
    - name: api
      port: {{ .Values.containerPort }}
      targetPort: {{ .Values.containerPort }}
      protocol: TCP
    # li7: the aria-ask sidecar (the ASK surface).
    - name: ask
      port: 8090
      targetPort: 8090
      protocol: TCP
"""

STRATEGY_OLD = """          strategy:
            type: RollingUpdate
            rollingUpdate:
              maxSurge: 1
              maxUnavailable: 0
"""

STRATEGY_NEW = """          strategy:
            type: RollingUpdate
            rollingUpdate:
              # li7 (injected by inject-sidecars.py): the node is
              # memory-tight (bible 51 Gi + pages 8 Gi + co-tenants ≈ 61 Gi
              # of 61.5 Gi allocatable) — NO SURGE: an old aria pod and its
              # replacement (~0.6 Gi each) may never both be scheduled.
              maxSurge: 0
              maxUnavailable: 1
"""

# The vLLM endpoint is only reachable through a loopback SSH tunnel on the
# li7 host (the domain maps to 127.0.0.1 in the host /etc/hosts; the tunnel
# is an `ssh -R` session, loopback-bound by the sshd GatewayPorts default).
# Pods resolve the domain via cluster DNS instead — so alias it to the node
# IP, and let vllm-pod-bridge.service (a socat on the node) forward
# node-IP:8902 -> 127.0.0.1:8902. See deploy/li7/SECRETS.md.
HOSTALIASES_BLOCK = """      # li7 (injected by inject-sidecars.py): the vLLM model registry URL
      # (gpu.datalab.siemens.com:8902) is a loopback SSH tunnel on the li7
      # host — pods cannot see the host's /etc/hosts entry, so alias the
      # domain to the node IP (socat bridge: vllm-pod-bridge.service).
      hostAliases:
        - ip: 192.168.11.63
          hostnames:
            - gpu.datalab.siemens.com
"""

VOLUMES_ANCHOR = "\n      volumes:\n"

INGRESS_OLD = """        paths:
          - path: /
            pathType: Prefix
            backend:
              service:
                name: {{ include "aria.fullname" $root }}
                port:
                  number: {{ $root.Values.containerPort }}
"""

INGRESS_NEW = """        paths:
          # li7 (injected by inject-sidecars.py): the ASK surface (the
          # aria-ask sidecar) owns the Alexa endpoints; the brain owns the
          # rest (REST, MCP, chat, A2A, docs).
          - path: /alexa
            pathType: Prefix
            backend:
              service:
                name: {{ include "aria.fullname" $root }}
                port:
                  number: 8090
          - path: /stream
            pathType: Prefix
            backend:
              service:
                name: {{ include "aria.fullname" $root }}
                port:
                  number: 8090
          - path: /art
            pathType: Prefix
            backend:
              service:
                name: {{ include "aria.fullname" $root }}
                port:
                  number: 8090
          - path: /
            pathType: Prefix
            backend:
              service:
                name: {{ include "aria.fullname" $root }}
                port:
                  number: {{ $root.Values.containerPort }}
"""


def main() -> int:
    helm_dir = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else ".")
    tag = sys.argv[2] if len(sys.argv) > 2 else "latest"
    sidecar = SIDECAR.replace("__TAG__", tag)
    dep = helm_dir / "templates" / "deployment.yaml"
    text = dep.read_text()

    if "aria-ask" not in text:
        if BRAIN_MOUNTS_OLD not in text:
            print(f"ERROR: anchor not found in {dep} (chart changed? re-check the injection point)")
            return 1
        # Brain mounts (always-on hostPaths) + the sidecar, in one pass.
        dep.write_text(text.replace(BRAIN_MOUNTS_OLD, BRAIN_MOUNTS_PRELUDE + sidecar, 1))
        print(f"injected the aria-ask sidecar ({tag}) + the li7 hostPath mounts into {dep}")

    if "name: media" not in text:
        if VOLUMES_OLD not in text:
            print(f"ERROR: volumes anchor not found in {dep} (chart changed?)")
            return 1
        dep.write_text(dep.read_text().replace(VOLUMES_OLD, VOLUMES_NEW, 1))
        print(f"injected the media hostPath volume into {dep}")

    svc = helm_dir / "templates" / "service.yaml"
    stext = svc.read_text()
    if "name: ask" not in stext:
        if not re.search(r"  ports:\n", stext):
            print(f"ERROR: no ports block in {svc} (chart changed?)")
            return 1
        stext = re.sub(r"  ports:\n(?:[ \t]+.*\n)+", SVC_PORTS_NEW, stext, count=1)
        svc.write_text(stext)
        print(f"normalized service ports in {svc}")

    if "maxSurge: 0" not in text:
        if STRATEGY_OLD in text:
            dep.write_text(dep.read_text().replace(STRATEGY_OLD, STRATEGY_NEW, 1))
            print(f"normalized the rollout strategy (no surge) in {dep}")
        else:
            print(f"NOTE: strategy anchor not found in {dep} (chart changed?)")

    if "hostAliases" not in dep.read_text():
        if VOLUMES_ANCHOR in dep.read_text():
            dep.write_text(dep.read_text().replace(VOLUMES_ANCHOR, "\n" + HOSTALIASES_BLOCK + "      volumes:\n", 1))
            print(f"injected the vLLM hostAlias into {dep}")
        else:
            print(f"NOTE: pod-spec volumes anchor not found in {dep} (chart changed?)")

    ing = helm_dir / "templates" / "ingress.yaml"
    itext = ing.read_text()
    if "/alexa" not in itext:
        if INGRESS_OLD in itext:
            ing.write_text(itext.replace(INGRESS_OLD, INGRESS_NEW, 1))
            print(f"injected the ingress path split into {ing}")
        else:
            print(f"NOTE: ingress path anchor not found in {ing} (already split or chart changed?)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
